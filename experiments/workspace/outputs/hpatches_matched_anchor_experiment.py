"""HPatches task audit with AA and consistent laws sharing a 2x kernel.

This is a controlled *kernel-model* experiment, not a bitwise emulation of
Pillow/OpenCV. Both laws use the same periodic Fourier grid and the same
finite-support AA interpolant at factor two. The consistent camera transfer
is generated by the dyadic telescope of that common half-scale slice.
"""

from __future__ import annotations

import argparse
import csv
import json
from functools import lru_cache
from pathlib import Path

import cv2
import numpy as np

import hpatches_geometry_experiment as geometry


BASES = ("linear tent", "Keys cubic a=-0.5")
GAUSSIAN_BASE = "Gaussian (x2 Nyquist MTF matched)"
LAWS = ("AA stretch", "consistent telescope")
PATHS = ("full direct", "anchor direct", "anchor chain")


@lru_cache(maxsize=1)
def cubic_fourier_table() -> tuple[np.ndarray, np.ndarray]:
    x = np.linspace(0.0, 2.0, 2049, dtype=np.float64)
    a = -0.5
    kernel = np.where(
        x < 1.0,
        (a + 2) * x**3 - (a + 3) * x**2 + 1,
        a * x**3 - 5 * a * x**2 + 8 * a * x - 4 * a,
    )
    frequencies = np.linspace(0.0, np.pi, 4097, dtype=np.float64)
    integrate = np.trapezoid if hasattr(np, "trapezoid") else np.trapz
    values = 2 * integrate(
        np.cos(frequencies[:, None] * x[None, :]) * kernel[None, :],
        x,
        axis=1,
    )
    values /= values[0]
    return frequencies, values


def base_transfer(base: str, omega: np.ndarray) -> np.ndarray:
    absolute = np.abs(omega)
    if np.any(absolute > np.pi + 1e-8):
        raise ValueError("outside the retained Fourier band")
    if base == "linear tent":
        return np.sinc(absolute / (2 * np.pi)) ** 2
    if base == "Keys cubic a=-0.5":
        frequency_grid, values = cubic_fourier_table()
        return np.interp(absolute, frequency_grid, values)
    if base == GAUSSIAN_BASE:
        return np.exp(-gaussian_alpha() * absolute**2)
    raise KeyError(base)


@lru_cache(maxsize=1)
def gaussian_alpha() -> float:
    """Match Gaussian x2 Nyquist MTF to the two bases' geometric mean.

    This is fixed by the anchor filters, not by any downstream task result.
    The Gaussian symbol is exp(-alpha * omega**2), where alpha = sigma**2/2.
    """
    anchor_omega = np.array(np.pi, dtype=np.float64)
    linear = float(base_transfer("linear tent", anchor_omega))
    cubic = float(base_transfer("Keys cubic a=-0.5", anchor_omega))
    target = np.sqrt(linear * cubic)
    return float(-np.log(target) / np.pi**2)


def telescope_camera(base: str, omega: np.ndarray, terms: int = 16) -> np.ndarray:
    result = np.ones_like(omega, dtype=np.float64)
    for index in range(terms):
        result *= base_transfer(base, omega / 2**index)
    return result


@lru_cache(maxsize=8192)
def transfer_axis(
    input_length: int, output_length: int, base: str, law: str
) -> tuple[np.ndarray, np.ndarray]:
    if output_length > input_length or output_length % 2 != 1:
        raise ValueError("this audit coarsens into odd Fourier grids")
    mode = np.arange(-(output_length // 2), output_length // 2 + 1)
    omega = 2 * np.pi * mode / input_length
    ratio = input_length / output_length
    if law == "AA stretch":
        multiplier = base_transfer(base, ratio * omega)
    elif law == "consistent telescope":
        multiplier = telescope_camera(base, ratio * omega) / telescope_camera(base, omega)
    else:
        raise KeyError(law)
    input_offset = -(input_length - 1) / 2
    output_offset = -ratio * (output_length - 1) / 2
    phase = np.exp(1j * omega * (output_offset - input_offset))
    return multiplier, phase


def spectral_resize(
    image: np.ndarray, shape: tuple[int, int], base: str, law: str
) -> np.ndarray:
    input_height, input_width = image.shape
    output_height, output_width = shape
    multiplier_y, phase_y = transfer_axis(input_height, output_height, base, law)
    multiplier_x, phase_x = transfer_axis(input_width, output_width, base, law)
    spectrum = np.fft.fftshift(np.fft.fft2(image))
    y_start = input_height // 2 - output_height // 2
    x_start = input_width // 2 - output_width // 2
    cropped = spectrum[
        y_start : y_start + output_height,
        x_start : x_start + output_width,
    ]
    multiplier = (
        multiplier_y[:, None]
        * multiplier_x[None, :]
        * phase_y[:, None]
        * phase_x[None, :]
        * (output_height / input_height)
        * (output_width / input_width)
    )
    return np.fft.ifft2(np.fft.ifftshift(cropped * multiplier)).real.astype(np.float32)


def trim_to_exact_half(image: np.ndarray) -> np.ndarray:
    height, width = image.shape
    height -= (height - 2) % 4
    width -= (width - 2) % 4
    return image[:height, :width]


def geometric_path(
    source: tuple[int, int], target: tuple[int, int], steps: int
) -> list[tuple[int, int]]:
    shapes = [source]
    for index in range(1, steps):
        portion = index / steps
        shapes.append(
            tuple(
                geometry.nearest_odd(
                    dimension * (endpoint / dimension) ** portion
                )
                for dimension, endpoint in zip(source, target)
            )
        )
    shapes.append(target)
    if any(not (a[0] > b[0] and a[1] > b[1]) for a, b in zip(shapes, shapes[1:])):
        raise ValueError(f"nondecreasing path {shapes}")
    return shapes


def features(
    image: np.ndarray,
    original_shape: tuple[int, int],
    sift: cv2.SIFT,
) -> tuple[np.ndarray, np.ndarray | None]:
    keypoints, descriptors = sift.detectAndCompute(geometry.to_uint8(image), None)
    points = geometry.keypoints_to_original(keypoints, original_shape, image.shape)
    return points, descriptors


def ransac_threshold(
    original_shape: tuple[int, int], final_shape: tuple[int, int]
) -> float:
    effective_scale = np.sqrt(
        (final_shape[0] / original_shape[0])
        * (final_shape[1] / original_shape[1])
    )
    return 1.25 / effective_scale


def write_rows(path: Path, rows: list[dict]) -> None:
    if not rows:
        return
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def run(args: argparse.Namespace) -> None:
    cv2.setNumThreads(1)
    dataset = args.dataset.resolve()
    sequences = sorted(
        directory for directory in dataset.iterdir()
        if directory.is_dir() and (directory / "1.ppm").exists()
    )
    if args.max_sequences:
        sequences = sequences[: args.max_sequences]
    args.output.mkdir(parents=True, exist_ok=True)
    sift = cv2.SIFT_create(nfeatures=1500, contrastThreshold=0.01)
    task_rows: list[dict] = []
    image_rows: list[dict] = []

    for sequence_index, directory in enumerate(sequences, start=1):
        originals = {
            number: trim_to_exact_half(geometry.load_grayscale(directory / f"{number}.ppm"))
            for number in range(1, 7)
        }
        for base in BASES:
            extracted: dict[tuple[int, str, str], tuple[np.ndarray, np.ndarray | None]] = {}
            final_shapes: dict[tuple[int, int], tuple[int, int]] = {}
            for number, original in originals.items():
                half_shape = tuple(dimension // 2 for dimension in original.shape)
                anchor_aa = spectral_resize(original, half_shape, base, "AA stretch")
                anchor_consistent = spectral_resize(original, half_shape, base, "consistent telescope")
                image_rows.append(
                    {
                        "sequence": directory.name,
                        "type": directory.name[0],
                        "image": number,
                        "base": base,
                        "factor": 2,
                        "comparison": "anchor consistency vs AA",
                        "nrmse_percent": geometry.image_disagreement(anchor_aa, anchor_consistent),
                    }
                )
                # The *same literal array* enters both post-anchor branches.
                extracted[(number, "shared", "anchor")] = features(anchor_aa, original.shape, sift)
                for factor in args.factors:
                    final_shape = tuple(
                        geometry.nearest_odd(dimension / factor)
                        for dimension in original.shape
                    )
                    final_shapes[(number, factor)] = final_shape
                    path = geometric_path(half_shape, final_shape, 4)
                    law_anchor_direct: dict[str, np.ndarray] = {}
                    for law in LAWS:
                        full_direct = spectral_resize(original, final_shape, base, law)
                        anchor_direct = spectral_resize(anchor_aa, final_shape, base, law)
                        chain = anchor_aa
                        for shape in path[1:]:
                            chain = spectral_resize(chain, shape, base, law)
                        images = {
                            "full direct": full_direct,
                            "anchor direct": anchor_direct,
                            "anchor chain": chain,
                        }
                        law_anchor_direct[law] = anchor_direct
                        image_rows.extend(
                            [
                                {
                                    "sequence": directory.name,
                                    "type": directory.name[0],
                                    "image": number,
                                    "base": base,
                                    "factor": factor,
                                    "comparison": f"{law}: full vs anchor direct",
                                    "nrmse_percent": geometry.image_disagreement(full_direct, anchor_direct),
                                },
                                {
                                    "sequence": directory.name,
                                    "type": directory.name[0],
                                    "image": number,
                                    "base": base,
                                    "factor": factor,
                                    "comparison": f"{law}: anchor direct vs chain",
                                    "nrmse_percent": geometry.image_disagreement(anchor_direct, chain),
                                },
                            ]
                        )
                        for path_name, image in images.items():
                            extracted[(number, law, f"{factor}:{path_name}")] = features(
                                image, original.shape, sift
                            )
                    image_rows.append(
                        {
                            "sequence": directory.name,
                            "type": directory.name[0],
                            "image": number,
                            "base": base,
                            "factor": factor,
                            "comparison": "consistent vs AA: anchored direct",
                            "nrmse_percent": geometry.image_disagreement(
                                law_anchor_direct["AA stretch"],
                                law_anchor_direct["consistent telescope"],
                            ),
                        }
                    )
            for target_number in range(2, 7):
                truth = np.loadtxt(directory / f"H_1_{target_number}", dtype=np.float64).reshape(3, 3)
                for factor in (2, *args.factors):
                    if factor == 2:
                        cases = [("shared", "anchor")]
                    else:
                        cases = [(law, path_name) for law in LAWS for path_name in PATHS]
                    for law, path_name in cases:
                        reference = extracted[(1, law, "anchor" if factor == 2 else f"{factor}:{path_name}")]
                        target = extracted[(target_number, law, "anchor" if factor == 2 else f"{factor}:{path_name}")]
                        final_shape = (
                            tuple(dimension // 2 for dimension in originals[target_number].shape)
                            if factor == 2 else final_shapes[(target_number, factor)]
                        )
                        metrics = geometry.score_pair(
                            reference,
                            target,
                            truth,
                            originals[1].shape,
                            originals[target_number].shape,
                            final_shape,
                            ransac_threshold(originals[target_number].shape, final_shape),
                        )
                        task_rows.append(
                            {
                                "sequence": directory.name,
                                "type": directory.name[0],
                                "target": target_number,
                                "base": base,
                                "factor": factor,
                                "law": law,
                                "path": path_name,
                                **metrics,
                            }
                        )
        if sequence_index % 5 == 0 or sequence_index == len(sequences):
            write_rows(args.output / "task_results.csv", task_rows)
            write_rows(args.output / "image_results.csv", image_rows)
            print(f"processed {sequence_index}/{len(sequences)} sequences", flush=True)

    protocol = {
        "dataset": str(dataset),
        "sequences": len(sequences),
        "base_interpolants": BASES,
        "laws": LAWS,
        "anchor_factor": 2,
        "hard_factors": args.factors,
        "anchor_definition": "same spectral AA half-scale kernel; source dimensions trimmed to 2 modulo 4",
        "anchor_image": "one literal AA anchor array shared by both post-anchor laws",
        "camera_completion": "dyadic telescope of the common half-scale slice, 16 terms",
        "model_only": "not bitwise Pillow/OpenCV; both laws use identical periodic Fourier grid",
        "aliasing": "retained Fourier projection removes high-frequency aliasing in this kernel-law control",
        "sift": {"nfeatures": 1500, "contrastThreshold": 0.01},
        "matcher": "mutual Lowe ratio 0.8",
        "ransac_threshold_output_px": 1.25,
        "homography_success_threshold_output_px": 2.5,
    }
    (args.output / "protocol.json").write_text(json.dumps(protocol, indent=2))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dataset", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--factors", nargs="+", type=int, default=[8, 12, 16])
    parser.add_argument("--max-sequences", type=int, default=0)
    run(parser.parse_args())


if __name__ == "__main__":
    main()
