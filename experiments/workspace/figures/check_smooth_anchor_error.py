"""Exploratory smooth calibration-error check for the frozen shared-solver test.

Both arms receive the SAME erroneous x2 anchor. The optical captures, grid,
solver, eta, scenes, and paired noise draws match check_shared_solver_transfer.
This file does not alter the paper experiment or its frozen results.
"""
from pathlib import Path
import hashlib
import json
import time

import numpy as np
from scipy import linalg

import check_shared_solver_transfer as base
import check_psf_misspec_transfer as misspec


OUT = base.ROOT / "outputs/smooth_anchor_error_2026-10-01"
LEVELS = [0., .005, .01, .02, .05]
PILOT_SEEDS = [11, 23, 37, 53, 71]
# The added draws can all attain 5% anchor error with positive spatial-PSF
# modulation (amplitude<.95) for both cameras. This reachability pre-screen is
# disclosed; these are sensitivity draws, not an unbiased population CI.
SEEDS = PILOT_SEEDS + [100, 101, 102, 105, 106, 107, 108, 109, 110, 111,
                       112, 113, 114, 115, 116]
ETA = .01
W = 2 * np.pi * np.fft.fftfreq(base.N)


def relative_errors(reference, estimate, h):
    """Weighted Fourier L2 and unweighted spatial circular-kernel L2."""
    a, b = reference(W), estimate(W)
    weight = abs(h(W))**2
    passband = np.sqrt(np.sum(weight * abs(b-a)**2) / np.sum(weight * abs(a)**2))
    spatial = np.linalg.norm(np.fft.ifft(b-a)) / np.linalg.norm(np.fft.ifft(a))
    return float(passband), float(spatial)


def coefficients(seed):
    rng = np.random.default_rng(seed)
    c = rng.standard_normal(3)
    return c / np.sum(abs(c))


def seeds_for_level(level):
    return [-1] if level == 0 else (PILOT_SEEDS if level == .005 else SEEDS)


def direct_anchor(reference, c, level, h):
    """Even, C-infinity, DC-preserving noise directly on the x2 anchor.

    This is a normalized effective transfer function, NOT guaranteed to be
    generated by a nonnegative spatial PSF or a fixed aperture.
    """
    def shape(z):
        z = np.asarray(z)
        return sum(c[k-1] * (np.cos(k*z)-1) for k in [1, 2, 3])

    unit = lambda z: reference(z) * (1 + shape(z))
    unit_error, _ = relative_errors(reference, unit, h)
    amplitude = level / unit_error if unit_error else 0.
    estimate = lambda z: reference(z) * (1 + amplitude * shape(z))
    return estimate, amplitude


def modulated_psf(h, c, amplitude):
    """Spatial p_est(x) proportional to p_true(x)*(1+a*g(x)).

    g is a smooth even cosine series. |g(x)|<=1, so a<1 guarantees a
    nonnegative normalized effective PSF when p_true itself is nonnegative.
    Its OTF is a short analytic sum of shifted true OTFs.
    """
    frequencies = [.45, .90, 1.35]
    normalizer = 1 + amplitude * sum(c[k] * h(frequencies[k]) for k in range(3))

    def estimate(z):
        z = np.asarray(z)
        result = h(z).copy()
        for k, frequency in enumerate(frequencies):
            result += amplitude * c[k] / 2 * (h(z-frequency) + h(z+frequency))
        return result / normalizer
    return estimate


def psf_anchor(reference, h, c, level):
    if not level:
        return reference, 0.
    lo, hi = 0., .95
    anchor_at = lambda a: misspec.anchor_from(modulated_psf(h, c, a))
    achievable, _ = relative_errors(reference, anchor_at(hi), h)
    if achievable < level:
        raise ValueError(f"Cannot reach {level:.3%} anchor error; max {achievable:.3%}")
    for _ in range(34):
        mid = (lo+hi)/2
        error, _ = relative_errors(reference, anchor_at(mid), h)
        if error < level:
            lo = mid
        else:
            hi = mid
    amplitude = (lo+hi)/2
    return anchor_at(amplitude), amplitude


def score(rows):
    result = []
    for family in ["Gaussian", "Pupil"]:
        for mode in ["direct_anchor", "spatial_psf"]:
            for level in LEVELS:
                seeds = seeds_for_level(level)
                for scale in [2, 3, 4]:
                    for noise in [0, 1]:
                        seed_gains, seed_psnrs = [], []
                        for seed in seeds:
                            gain_image, psnr_image = [], []
                            for name in base.NAMES:
                                ours = np.mean([r["psnr_y"] for r in rows if
                                    (r["family"], r["mode"], r["target_error"], r["seed"],
                                     r["scale"], r["noise_255"], r["image"], r["arm"]) ==
                                    (family, mode, level, seed, scale, noise, name, "ours")])
                                aa = np.mean([r["psnr_y"] for r in rows if
                                    (r["family"], r["mode"], r["target_error"], r["seed"],
                                     r["scale"], r["noise_255"], r["image"], r["arm"]) ==
                                    (family, mode, level, seed, scale, noise, name, "aa")])
                                gain_image.append(ours-aa)
                                psnr_image.append([ours, aa])
                            seed_gains.append(float(np.mean(gain_image)))
                            seed_psnrs.append(np.mean(psnr_image, axis=0).tolist())
                        result.append(dict(family=family, mode=mode, target_error=level,
                            scale=scale, noise_255=noise, seed_gains=seed_gains,
                            gain_mean=float(np.mean(seed_gains)),
                            gain_seed_sd=float(np.std(seed_gains, ddof=1)) if len(seed_gains)>1 else 0.,
                            gain_range=[float(min(seed_gains)), float(max(seed_gains))],
                            positive_seeds=int(sum(g > 0 for g in seed_gains)),
                            negative_seeds=int(sum(g < 0 for g in seed_gains)),
                            negative_seed_fraction=float(np.mean(np.array(seed_gains) < 0)),
                            n_seeds=len(seed_gains), seed_psnrs=seed_psnrs))
    return result


def main():
    started = time.monotonic()
    OUT.mkdir(parents=True, exist_ok=True)
    frozen = json.loads((base.OUT / "results.json").read_text())
    frozen_index = {(r["family"], r["scale"], r["image"], r["noise_255"],
                     r["draw"], r["eta"], r["arm"]): r for r in frozen}
    protocol = dict(parent_script=str(Path(base.__file__).relative_to(base.ROOT)),
        parent_sha256=hashlib.sha256(Path(base.__file__).read_bytes()).hexdigest(),
        script_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        frozen_results_sha256=hashlib.sha256((base.OUT / "results.json").read_bytes()).hexdigest(),
        images=base.NAMES, n=base.N, families=["Gaussian", "Pupil"],
        scales=[2, 3, 4], modes=["direct_anchor", "spatial_psf"],
        target_relative_anchor_errors=LEVELS, seeds=SEEDS,
        seeds_for_half_percent=PILOT_SEEDS,
        seed_reachability_note="15 added seeds were prescreened to attain 5% weighted anchor error with positive spatial-PSF modulation for both cameras; not a population-random CI",
        noise_255=[0, 1], noise_repeats=3, eta=ETA,
        boundary="periodic", grid="centered, S*j+(S-1)/2",
        truth="independent unperturbed-PSF captures, never altered",
        common_solver="same finite forward matrix model and SVD/Tikhonov eta",
        error_metric="sqrt(sum |H_true(w)|^2 |U_est-U_true|^2 / sum |H_true(w)|^2 |U_true|^2) on N-point FFT grid",
        spatial_metric="||ifft(U_est-U_true)||_2 / ||ifft(U_true)||_2 on circular N-tap kernel",
        direct="smooth even cosine modulation of estimated x2 U; U(0)=1; physical PSF not guaranteed",
        psf="positive smooth even cosine modulation of true effective spatial PSF, normalized; not necessarily same finite aperture",
        data_sha256={im: hashlib.sha256((base.DATA / f"{im}_hr.npy").read_bytes()).hexdigest()
                     for im in base.NAMES})
    (OUT / "protocol.json").write_text(json.dumps(protocol, indent=2))

    rows, diagnostics = [], []
    for family in ["Gaussian", "Pupil"]:
        h = misspec.estimated_camera(family, 0.)
        reference = misspec.anchor_from(h)
        captures = misspec.observations(family, h)
        if family == "Gaussian":
            sigma_plus_ten = misspec.anchor_from(misspec.estimated_camera(family, .1))
            sigma_pw, sigma_spatial = relative_errors(reference, sigma_plus_ten, h)
            diagnostics.append(dict(family=family, comparison="sigma_plus_10pct",
                passband_error=sigma_pw, spatial_error=sigma_spatial))
        for mode in ["direct_anchor", "spatial_psf"]:
            for level in LEVELS:
                seeds = seeds_for_level(level)
                for seed in seeds:
                    c = coefficients(seed) if seed >= 0 else np.zeros(3)
                    if mode == "direct_anchor":
                        estimated, amplitude = direct_anchor(reference, c, level, h)
                    else:
                        estimated, amplitude = psf_anchor(reference, h, c, level)
                    actual, spatial = relative_errors(reference, estimated, h)
                    assert abs(actual-level) < 1e-7, (family, mode, level, seed, actual)
                    assert abs(float(estimated(np.array([0.]))[0])-1.) < 1e-12
                    assert np.max(abs(estimated(W)-estimated(-W))) < 1e-10
                    recovered = misspec.recovered_from(estimated)
                    if level == 0:
                        assert np.max(abs(recovered(W)-h(W))) < 1e-9
                    x2 = base.axis_map(estimated, 2)
                    x2_aa = base.axis_map(lambda z: estimated(2*np.asarray(z)/2), 2)
                    assert np.array_equal(x2, x2_aa)
                    diagnostics.append(dict(family=family, mode=mode, target_error=level,
                        seed=seed, amplitude=amplitude, passband_error=actual,
                        spatial_error=spatial, x2_matrix_maxdiff=float(np.max(abs(x2-x2_aa))),
                        direct_anchor_min=float(np.min(estimated(W))),
                        psf_nonnegative_guarantee=(mode == "spatial_psf" and amplitude < 1)))
                    for factor in [2, 3, 4]:
                        def consistent(z):
                            if factor == 2:
                                return estimated(z)
                            den = recovered(z)
                            return np.divide(recovered(factor*np.asarray(z)), den,
                                out=np.zeros_like(den), where=abs(den) > 1e-15)
                        aa = lambda z: estimated(factor*np.asarray(z)/2)
                        d_ours = base.axis_map(consistent, factor)
                        d_aa = base.axis_map(aa, factor)
                        if factor == 2:
                            assert np.array_equal(d_ours, d_aa)
                        svds = {arm: linalg.svd(d, full_matrices=False)
                                for arm, d in [("ours", d_ours), ("aa", d_aa)]}
                        for ii, name in enumerate(base.NAMES):
                            truth, observed = captures[name, factor]
                            for noise in [0, 1]:
                                for rep in range(1 if noise == 0 else 3):
                                    rng = np.random.default_rng(200926 + 100*ii + 10*factor + rep)
                                    noisy = observed + (noise/255)*rng.standard_normal(observed.shape)
                                    for arm in ["ours", "aa"]:
                                        pred = base.solve(noisy, svds[arm], ETA)
                                        row = dict(family=family, mode=mode, target_error=level,
                                            seed=seed, scale=factor, image=name, noise_255=noise,
                                            draw=rep, eta=ETA, arm=arm,
                                            psnr_y=base.psnr(pred, truth, factor),
                                            psnr_y_raw=base.psnr(pred, truth, factor, False))
                                        rows.append(row)
                                        if level == 0:
                                            key = (family, factor, name, noise, rep, ETA, arm)
                                            for metric in ["psnr_y", "psnr_y_raw"]:
                                                assert abs(row[metric]-frozen_index[key][metric]) < 1e-8
            print(json.dumps(dict(family=family, mode=mode, completed=True)), flush=True)

    summary = score(rows)
    (OUT / "results.json").write_text(json.dumps(rows, indent=2))
    (OUT / "diagnostics.json").write_text(json.dumps(diagnostics, indent=2))
    (OUT / "summary.json").write_text(json.dumps(summary, indent=2))
    (OUT / "runtime.json").write_text(json.dumps(dict(seconds=time.monotonic()-started), indent=2))
    lines = ["# Smooth ×2-anchor error pilot", "",
        "Exploratory, not in the manuscript. Both arms use the same erroneous ×2 anchor; true captures, five Set5 scenes, fixed η=0.01 solver, grid, boundaries and paired noise draws are unchanged.", "",
        f"Gaussian σ+10% gives {sigma_pw:.2%} passband-weighted ×2-anchor error and {sigma_spatial:.2%} spatial-kernel L2 error.", "",
        "Passband error weights the Fourier squared difference by |H_true(ω)|²; spatial error is relative circular-kernel L2. The passband metric is the calibrated level below.", "",
        "The *direct-anchor* mode adds smooth even DC-preserving cosine error to U₂, with no guarantee of a nonnegative underlying PSF. The *spatial-PSF* mode multiplies the true effective PSF by a positive smooth even function and normalizes; it guarantees a nonnegative PSF but does not guarantee the same pupil/aperture support or a zero-free full-band OTF. Its anchor error is an induced consequence, not direct kernel noise.", "",
        "Twenty independently generated perturbation seeds at 1%, 2%, and 5% error (five at 0.5%); level zero is the frozen baseline. The added seeds were pre-screened only for the positive-PSF modulation's ability to attain 5% error, so the across-seed spread is descriptive, not a population confidence interval. Numbers below are mean camera-law minus AA-stretch PSNR (dB), seed SD, and negative-seed count, at noise 1/255.", "",
        "| Family | Perturbation | U₂ error | ×3 mean ± seed SD (negative seeds) | ×4 mean ± seed SD (negative seeds) |",
        "|---|---|---:|---:|---:|"]
    for family in ["Gaussian", "Pupil"]:
        for mode in ["direct_anchor", "spatial_psf"]:
            for level in LEVELS:
                entries = [next(s for s in summary if (s["family"], s["mode"], s["target_error"],
                            s["scale"], s["noise_255"]) == (family, mode, level, scale, 1))
                           for scale in [3, 4]]
                cells = [f'{e["gain_mean"]:+.2f} ± {e["gain_seed_sd"]:.2f} ({e["negative_seeds"]}/{e["n_seeds"]})' for e in entries]
                lines.append(f"| {family} | {mode} | {level:.1%} | {cells[0]} | {cells[1]} |")
    lines += ["", "Interpretation: target errors are calibrated on the ×2 anchor, rather than on an arbitrary Gaussian-width parameter. Error shape matters; no single tolerance threshold is implied. Full clean/noisy, seed ranges, ×2 tie, and per-image data are in JSON files.\n"]
    (OUT / "SUMMARY.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
